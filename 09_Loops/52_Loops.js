// For Loop
// Helps you to repeat a block of code a certain number of times

// ICU
// Initialize: Set a variable to a starting value
// Condition: Check if the variable meets a certain condition
// Update: Change the variable's value after each iteration using an increment or decrement operator


for (let i = 0; i < 10; i++) {
    console.log("I value with post increment:", i);
}

console.log("--------------------------------------------------");

for (let j = 0; j < 10; ++j) {
    console.log("J value with pre increment:", j);
}