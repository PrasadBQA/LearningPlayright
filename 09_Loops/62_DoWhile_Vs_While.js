let a = 10;
while (a < 10)
    {
        console.log(`Value of a is: ${a}`);
        a++;
    }
 //   console.log("This line will not be executed because the while loop condition is false from the start.");
// The above while loop will not execute because the condition (a < 10) is false from the start.

// Same with do while loop
let b = 10;
do
    {
        console.log(`Value of b is: ${b}`);
        b++;
    }while (b < 10);
// The above do while loop will execute once because the code block is executed before the condition is checked.

